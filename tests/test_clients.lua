test("under a client surface GameTooltip records the lines an addon adds, and a plain frame is no tooltip", function()
    restore()
    H.stubClient()
    T.eq(rawget(_G, "GameTooltip"), nil, "a stub with no surface has no GameTooltip")
    restore()
    H.stubClient({ client = "era" })
    local tip = GameTooltip
    T.ok(tip, "the client has GameTooltip")
    tip:SetOwner(UIParent, "ANCHOR_RIGHT")
    tip:SetText("Title"); tip:AddLine("one"); tip:AddDoubleLine("left", "right")
    T.eq(tip:NumLines(), 3)
    T.same(H.tooltipLines(tip), { { left = "Title" }, { left = "one" }, { left = "left", right = "right" } })
    T.eq(tip:IsShown(), false, "the game's tooltip starts hidden")
    tip:AddLine("red", 1, 0, 0, true); T.same(H.tooltipLines(tip)[4], { left = "red", color = { 1, 0, 0 }, wrap = true })
    tip:AddDoubleLine("a", "b", 1, 1, 1, 0, 1, 0); T.same(H.tooltipLines(tip)[5].rightColor, { 0, 1, 0 })
    tip:ClearLines(); tip:SetText("Title"); tip:AddLine("one"); tip:AddDoubleLine("left", "right")
    local odd = CreateFrame("gametooltip"); odd:AddLine("cased"); T.eq(#H.tooltipLines(odd), 1, "the kind is matched without regard to case")
    tip:SetOwner(UIParent, "ANCHOR_LEFT")
    T.eq(tip:NumLines(), 0, "SetOwner clears the lines"); T.eq(tip:GetOwner(), UIParent)
    tip:AddLine("x"); tip:ClearLines()
    T.same(H.tooltipLines(tip), {})
    local own = CreateFrame("GameTooltip", "MyTip", nil, "GameTooltipTemplate")
    own:AddLine("mine"); T.eq(#H.tooltipLines(own), 1); T.eq(#H.tooltipLines(tip), 0, "each tooltip has its own lines")
    T.eq(H.tooltipLines(CreateFrame("Frame")), nil); T.eq(CreateFrame("Frame").AddLine, nil, "a plain frame has no AddLine")
end)

test("the tooltip hook path follows the client: Era runs the OnTooltipSetItem script, Forever the TooltipDataProcessor post call", function()
    local function itemLink() return "|cffffffff|Hitem:6948::::::::10::::::::::|h[Hearthstone]|h|r" end
    restore()
    H.stubClient({ client = "era" })
    T.eq(rawget(_G, "TooltipDataProcessor"), nil, "Era has no TooltipDataProcessor")
    local fired = { script = 0, other = 0 }
    GameTooltip:HookScript("OnTooltipSetItem", function(tip) fired.script = fired.script + 1; fired.tip = tip end)
    GameTooltip:SetHyperlink("item:6948")
    T.eq(fired.script, 1, "the script hook runs at once"); T.eq(fired.tip, GameTooltip)
    GameTooltip:SetHyperlink(itemLink()); T.eq(fired.script, 2, "a full item link too")
    GameTooltip:SetHyperlink("spell:2061"); T.eq(fired.script, 2, "a spell link is no item")
    GameTooltip:SetItemByID(6948); T.eq(fired.script, 3)
    restore()
    H.stubClient({ client = "forever" })
    T.eq(type(TooltipDataProcessor), "table"); T.eq(type(Enum.TooltipDataType.Item), "number")
    T.raises(function() GameTooltip:HookScript("OnTooltipSetItem", function() end) end, "OnTooltipSetItem", "Forever has no such script to hook")
    GameTooltip:HookScript("OnShow", function() end) -- other scripts still hook
    local calls, data = 0, nil
    TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, function(tip, d) calls = calls + 1; data = d end)
    TooltipDataProcessor.AddTooltipPostCall(12345, function() calls = calls + 100 end)
    GameTooltip:SetHyperlink("item:6948")
    T.eq(calls, 1, "the item post call runs at once, and a call for another type does not"); T.eq(data.type, "item")
    GameTooltip:SetHyperlink("spell:2061"); T.eq(calls, 1)
    T.raises(function() TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, "no") end, "Usage")
    local handled = {}
    rawset(_G, "geterrorhandler", function() return function(e) handled[#handled + 1] = e end end)
    TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, function() error("post call broke", 0) end)
    local ranAfter = 0
    TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Item, function() ranAfter = ranAfter + 1 end)
    GameTooltip:SetHyperlink("item:6948")
    T.eq(handled[1], "post call broke", "a throwing post call goes to the error handler"); T.ok(ranAfter >= 1, "and the next one still runs")
    restore()
    T.eq(rawget(_G, "TooltipDataProcessor"), nil, "restore removes it"); T.eq(rawget(_G, "Enum"), nil, "and the Enum table the client made")
    H.stubClient({ client = "era" })
    local scripted = 0
    GameTooltip:SetScript("OnTooltipSetItem", function() scripted = scripted + 1 end)
    GameTooltip:SetHyperlink("item:6948"); T.eq(scripted, 1, "a script set with SetScript runs too")
    restore()
    local old = H.clientSurface("era"); old.tooltipHooks = nil -- a surface file from before the key: the script path, no processor
    H.stubClient({ client = old })
    local n = 0
    GameTooltip:HookScript("OnTooltipSetItem", function() n = n + 1 end); GameTooltip:SetHyperlink("item:1"); T.eq(n, 1)
end)

test("a frame of a listed type has only its type's methods, plus those of its listed templates", function()
    restore()
    H.stubClient({ client = "era" })
    local f = CreateFrame("Frame")
    T.eq(f.SetPointt, nil, "a typo reads nil")
    T.raises(function() f:SetPointt("CENTER") end, "SetPointt", "and calling it fails")
    T.eq(type(f.SetPoint), "function")
    T.eq(type(CreateFrame("Button").SetText), "function")
    T.eq(CreateFrame("Frame").SetText, nil, "a plain Frame has no SetText")
    local b = CreateFrame("Frame", nil, nil, "BackdropTemplate")
    T.eq(type(b.SetBackdrop), "function", "the template's mixin method"); T.eq(b.SetBackdropp, nil, "a typo on a templated frame reads nil")
    T.raises(function() b:SetBackdropp({}) end, "SetBackdropp", "and calling it fails")
    T.eq(type(b.SetPoint), "function", "the type's own methods stay")
    local ok = CreateFrame("Button", nil, nil, "UIPanelButtonTemplate")
    T.eq(type(ok.SetText), "function"); T.ok(ok.Text, "a template's child key"); ok.Text:SetText("x"); T.eq(ok.Text, ok.Text, "and it is one child, not a new one per read"); T.ok(ok.Text.SetAnything, "that takes any method"); T.eq(ok.SetTextt, nil)
    local two = CreateFrame("Frame", nil, nil, "BackdropTemplate, UICheckButtonTemplate")
    T.ok(two.SetBackdrop and two.Text, "a list of templates adds each one's names")
    T.ok(CreateFrame("Button", nil, nil, "SecureActionButtonTemplate,UIPanelButtonTemplate").AnyMethodAtAll, "a template the surface does not list lets any method through")
    T.ok(CreateFrame("Frame", nil, nil, "MyAddonTemplate").AnyMethodAtAll, "so does an addon's own")
    local old = H.clientSurface("era"); old.templates = {}   -- a surface file from before templates were listed
    H.stubClient({ client = old })
    T.ok(CreateFrame("Frame", nil, nil, "BackdropTemplate").SetBackdropp, "an older surface keeps the old rule: a templated frame takes any method")
    T.eq(UIParent:CreateTexture().SetText, nil, "a texture has no SetText")
end)

