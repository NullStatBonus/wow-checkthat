-- The Lua 5.1 scanner (tools/lua51_check.lua): each finding kind, and code that must pass.
local _, test, T, finish = dofile("tests/harness.lua")()
local L = dofile("tools/lua51_check.lua")

local function find(text) return L.checkText(text, "t.lua") end
local function one(text, want)
    local r = find(text)
    T.eq(#r, 1, table.concat(r, " | "))
    T.ok(r[1]:find(want, 1, true), r[1])
    return r[1]
end

test("goto as a statement fails with file and line", function()
    T.eq(one("local a = 1\nfor i = 1, 2 do\n  goto done\nend", "rejects goto"):match("^t.lua:(%d+):"), "3")
end)
test("a label fails", function() one("do ::top:: end", "rejects ::") end)
test("hex, z and u escapes in a short string fail, each with its own text", function()
    one([[local s = "\x41"]], "\\x")
    one([[local s = 'a\z b']], "\\z")
    one([[local s = "\u{48}"]], "\\u")
end)
test("number suffixes LL, ULL and i fail", function()
    one("local n = 10LL", "suffix LL")
    one("local n = 5ull", "suffix ull")
    one("local n = 3i", "suffix i")
end)
test("numerals LuaJIT reads and Lua 5.1 rejects fail, whole numeral at a time", function()
    one("local n = 0x1p2i", "hex number")
    one("local n = 0x1p4", "hex number")
    one("local n = 0x1.8", "hex number")
    one("local n = 0b1010", "binary number")
    one("local n = 1_000", "_ inside a number")
    T.eq(#find("local n = 0xFF + 0x1e5 + 1e+5 + 3.5e2 + 0xA"), 0)
end)
test("a CR-only line ending ends a comment and counts as a line", function()
    T.eq(one("-- comment\rlocal a = 1\rgoto done", "rejects goto"):match("^t.lua:(%d+):"), "3")
    T.eq(one("a = 1\r\n-- c\n\rgoto done", "rejects goto"):match("^t.lua:(%d+):"), "3")
end)
test("a decimal escape, an escaped backslash before x, and normal numbers pass", function()
    T.eq(#find([[local s = "\065\\x41\n" local n = 0x1F + 1e5 + 2.5 + .5 + 3]]), 0)
end)
test("comments and long strings are skipped, and the line count stays right across them", function()
    T.eq(#find("-- goto x\n--[[ goto y\n::z:: \\x ]]\nlocal s = [==[ goto a ]] ::b:: 5LL ]==]\n--[==[\n10LL\n]==]"), 0)
    T.eq(one("--[[\n\n]]\nlocal s = [[\n\n]]\ngoto x", "goto"):match("^t.lua:(%d+):"), "7")
end)
test("goto used as a name passes", function()
    T.eq(#find("local goto = 1\nlocal t = { goto = 2 }\nt.goto = 3\nlocal x = t:goto()\ngoto = 4"), 0)
end)
test("goto used as a name after an operator passes, and goto at a statement start fails", function()
    T.eq(#find("local x = goto\nfoo()"), 0)
    T.eq(#find("local t = { a, goto }\nf(goto, goto)\nreturn goto\nx = a + goto\nlocal y = t[goto]"), 0)
    one("f()\ngoto done", "rejects goto")
    one("if a then goto done end", "rejects goto")
    one("x = 1; goto done", "rejects goto")
    one("local n = 1\ngoto done", "rejects goto")
    T.eq(#find("do ::a:: goto a end"), 2, "the label and the goto each count")
end)
test("a [[ inside a [[ ]] string or comment fails with the line, leveled brackets pass", function()
    T.eq(one("local a = 1\nlocal s = [[ x\n [[ y ]]", "nesting"):match("^t.lua:(%d+):"), "3")
    one("--[[ a [[ b ]]", "nesting")
    T.eq(#find("local s = [=[ [[ x ]] ]=]\n--[==[ [[ ]==]\nlocal t = [[ [ [x] ]]"), 0)
end)
test("a string that holds goto or :: passes", function() T.eq(#find([[local s = "goto x ::y:: 5LL"]]), 0) end)
test("an unreadable file is a finding", function() T.ok(L.check("tests/fixtures/none.lua")[1]:find("cannot read")) end)
test("the command line fails on a finding and passes on clean code", function()
    local p = io.popen("luajit tools/lua51_check.lua tests/fixtures/MockAddon/Goto.lua 2>&1"); local out = p:read("*a"); p:close()
    T.ok(out:find("Goto.lua:3: Lua 5.1 rejects goto", 1, true), out)
    local ok = os.execute("luajit tools/lua51_check.lua tests/fixtures/MockAddon/MockAddon_Vanilla.toc")
    T.ok(ok == 0 or ok == true, "the fixture TOC is clean")
end)
test("--globals reports a banned global that code reads, not a field of the same name", function()
    local path = os.tmpname()
    local f = io.open(path, "w"); f:write("local t = { os = 1 }\nlocal a = t.os\nlocal b = io.open\n"); f:close()
    local p = io.popen("luajit tools/lua51_check.lua --globals " .. path .. " 2>&1"); local out = p:read("*a"); p:close()
    os.remove(path)
    T.ok(out:find("reads the global io", 1, true), out)
    T.ok(not out:find("global os", 1, true), out)
end)
test("--globals catches _G.io and _G[\"os\"], not _G.other", function()
    local path = os.tmpname()
    local f = io.open(path, "w"); f:write('local a = _G.io\nlocal b = _G["os"].x\nlocal c = _G.fine\n'); f:close()
    local p = io.popen("luajit tools/lua51_check.lua --globals " .. path .. " 2>&1"); local out = p:read("*a"); p:close()
    os.remove(path)
    T.ok(out:find("reads the global io", 1, true), out)
    T.ok(out:find("reads the global os", 1, true), out)
    T.ok(not out:find("fine", 1, true), out)
end)
finish()
