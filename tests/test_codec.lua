local ns, test, T, finish, H = dofile("tests/harness.lua")()
H.plain(ns)
local plan = { kind = "plan", ct = 1, title = "t", n = { 1, 2, { x = "y" } } }
test("codec round trip", function()
    local s = assert(ns.Codec.Encode(plan))
    T.ok(s:find("^!CT1!%x%x%x%x%x%x%x%x!"), "prefix")
    local back = assert(ns.Codec.Decode(s))
    T.ok(T.deepEq(back, plan), "deep equal")
end)
test("codec rejects corrupt checksum without state change", function()
    local s = assert(ns.Codec.Encode(plan))
    local bad = s:gsub("^(!CT1!)%x%x%x%x%x%x%x%x", "%100000000")
    local v, err = ns.Codec.Decode(bad)
    T.ok(v == nil and err:find("checksum"), err)
end)
test("codec rejects unknown version and garbage", function()
    T.ok(ns.Codec.Decode("!CT2!00000000!AAAA") == nil)
    T.ok(ns.Codec.Decode("hello") == nil)
    T.ok(ns.Codec.Decode("!CT1!00000000!\\") == nil)
end)
test("codec size cap", function()
    local v, err = ns.Codec.Decode("!CT1!00000000!" .. string.rep("A", 130000))
    T.ok(v == nil and err:find("too large"), err)
end)
test("codec tolerates wrapped body", function()
    local s = assert(ns.Codec.Encode(plan))
    local head, body = s:match("^(!CT1!%x+!)(.+)$")
    local wrapped = body:gsub("(....................)", "%1\n")
    T.ok(ns.Codec.Decode(head .. wrapped) ~= nil)
end)

test("damaged base64 never raises", function()
    for _, body in ipairs({ "====", "A===", "AA=A", "AAAA====", "==AA", "A=AA" }) do
        local ok, tbl, err = pcall(ns.Codec.Decode, "!CT1!00000000!" .. body)
        T.ok(ok, "raised on " .. body); T.ok(tbl == nil and err, "rejected " .. body)
    end
end)

local function bomb()
    local LD = ns.LibDeflate or LibStub("LibDeflate")
    return LD, LD:CompressDeflate(string.rep("a", 3000000), { level = 1 })
end
test("inflate stops at the output cap", function()
    local LD, packed = bomb()
    local out, status = LD:DecompressDeflate(packed, ns.Codec.LIMITS.inflated)
    T.ok(out == nil and status == -20, "stopped with status " .. tostring(status))
    T.ok(LD:DecompressDeflate(packed) ~= nil, "no limit still decodes")
end)
test("codec passes the cap to the decoder and reports too large", function()
    local LD, packed = bomb()
    local seen
    local real = LD.DecompressDeflate
    LD.DecompressDeflate = function(self, s, max) seen = max; return real(self, s, max) end
    local str = "!CT1!00000000!" .. ns.Codec.b64enc(packed)
    local v, err = ns.Codec.Decode(str)
    LD.DecompressDeflate = real
    T.ok(#str < ns.Codec.LIMITS.encoded, "string within the encoded cap")
    T.ok(seen == ns.Codec.LIMITS.inflated, "cap passed: " .. tostring(seen))
    T.ok(v == nil and err:find("too large"), err)
end)

finish()
